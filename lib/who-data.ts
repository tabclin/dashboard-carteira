// Interpolação linear entre pontos — loop reverso para compatibilidade
export function interpolateWho(table: WhoZRow[], x: number): WhoZRow | null {
  if (table.length === 0) return null
  let lo: WhoZRow | undefined
  for (let i = table.length - 1; i >= 0; i--) {
    if (table[i].x <= x) { lo = table[i]; break }
  }
  const hi = table.find(r => r.x > x)
  if (!lo) return { ...table[0], x }
  if (!hi) return { ...lo, x }
  const t = (x - lo.x) / (hi.x - lo.x)
  const l = (a: number, b: number) => +(a + t * (b - a)).toFixed(3)
  return {
    x,
    sd3n: l(lo.sd3n, hi.sd3n), sd2n: l(lo.sd2n, hi.sd2n),
    sd1n: l(lo.sd1n, hi.sd1n), sd0:  l(lo.sd0,  hi.sd0),
    sd1p: l(lo.sd1p, hi.sd1p), sd2p: l(lo.sd2p, hi.sd2p),
    sd3p: l(lo.sd3p, hi.sd3p),
  }
}

